#!/bin/bash
# Regenerates tools/kct-audit/apfnDispatch.tsv from ~/.cache/sogen-symbols/user32.i64
# via idasql. Run from the repository root.
#
# apfnDispatch is at user32 RVA 0x96070 (image base 0x180000000 → VA 0x180096070).
# 189 valid slots (indices 0..188); stride 8 bytes (qword function pointers).
# Uses the xrefs table to resolve each slot's function pointer to a name.
#
# Usage:
#   bash tools/kct-audit/dump_apfn.sh [path/to/user32.i64]

set -euo pipefail

IDB="${1:-$HOME/.cache/sogen-symbols/user32.i64}"
IDASQL="$HOME/idasql/q"
OUT="tools/kct-audit/apfnDispatch.tsv"

if [[ ! -f "$IDB" ]]; then
    echo "error: user32.i64 not found at $IDB" >&2
    exit 1
fi
if [[ ! -x "$IDASQL" ]]; then
    echo "error: idasql not found at $IDASQL" >&2
    exit 1
fi

echo "# apfnDispatch — Windows 11 user32.dll KernelCallbackTable (apfnDispatch at RVA 0x96070, image base 0x180000000)" > "$OUT"
echo "# Generated by tools/kct-audit/dump_apfn.sh from $(basename "$IDB")" >> "$OUT"
echo "# Columns: index<tab>fn_name<tab>category" >> "$OUT"

"$IDASQL" -s "$IDB" -q "
SELECT
  (x.from_ea - 0x180096070) / 8 AS idx,
  COALESCE(f.name, printf('0x%X', x.to_ea)) AS fn_name
FROM xrefs x
LEFT JOIN funcs f ON f.address = x.to_ea
WHERE x.from_ea >= 0x180096070 AND x.from_ea < 0x180096070 + 189*8
ORDER BY x.from_ea
" | grep -E '^\|\s*[0-9]+' | awk -F'|' '{
    idx = $2 + 0
    fn  = $3
    gsub(/^[[:space:]]+|[[:space:]]+$/, "", fn)

    # Determine category
    if (fn == "__ClientCallDummyCallback") {
        cat = "dummy"
    } else if (idx >= 130 && idx <= 188) {
        cat = "wndproc-thunk"
    } else if (fn ~ /^__fn/) {
        cat = "marshal-fn"
    } else {
        cat = "client-callback"
    }

    printf "%d\t%s\t%s\n", idx, fn, cat
}' >> "$OUT"

echo "Written $OUT ($(grep -c '^[0-9]' "$OUT") entries)"
